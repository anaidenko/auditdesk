import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stringify } from "yaml";

import type { SeverityName } from "@/engine/types";

import type { KeyEntry, KeyLocation } from "./fixtures";
import type { LineMap } from "./prep/strip";

export interface ChallengeMap {
    [challenge: string]: {
        aspect: string;
        checklistItem: string;
        /** Items an auditor may as rightly file it under. */
        alsoItems?: string[];
        severity: SeverityName;
        title: string;
        /** Why the challenge is left out of the key: by the fixture's own fix, not a defect. */
        skip?: string;
    };
}

const COVERED = /\.(ts|tsx|js|jsx|mjs|cjs)$/;
const VULN_LINE = /vuln-code-snippet vuln-line\s+(.+?)\s*(?:\*\/|-->)?\s*$/;

/**
 * The answer key of a fixture whose source marks its vulnerable lines (Juice Shop's coding
 * challenges): read from the upstream files' markers and written in the prepared tree's line
 * numbers, one entry per challenge. A challenge's consecutive marked lines form one range; a
 * distant one becomes another place the same defect shows. Challenges marked on the same lines
 * under the same items share an entry. Only languages v1 covers are keyed. A mapped challenge with
 * no marked line left in the prepared tree is refused: the prep removed more than its answers.
 */
export function buildKey(upstream: Record<string, string>, lineMap: LineMap, challenges: ChallengeMap, preparedTree: string): KeyEntry[] {
    const lines = new Map<string, number[]>();
    for (const [file, text] of Object.entries(upstream)) {
        if (!COVERED.test(file)) continue;
        text.split("\n").forEach((line, i) => {
            const keys = line.match(VULN_LINE)?.[1].split(/\s+/) ?? [];
            for (const key of keys) lines.set(`${file}\n${key}`, [...(lines.get(`${file}\n${key}`) ?? []), i + 1]);
        });
    }
    const locations = new Map<string, KeyLocation[]>();
    for (const [at, upstreamLines] of lines) {
        const [file, key] = at.split("\n");
        const map = lineMap.get(file);
        // A line the prep removed, alone or with its file, is no longer in the audited tree.
        const moved = upstreamLines.map(n => (map ? map(n) : n)).filter((n): n is number => n !== null);
        if (!moved.length) continue;
        const prepared = readFileSync(join(preparedTree, file), "utf8").split("\n");
        const ranges: [number, number][] = [];
        for (const n of moved) {
            const last = ranges.at(-1);
            if (last && n === last[1] + 1) last[1] = n;
            else ranges.push([n, n]);
        }
        const found = ranges.map(([startLine, endLine]) => ({ file, startLine, endLine, anchor: prepared[startLine - 1].trim() }));
        locations.set(key, [...(locations.get(key) ?? []), ...found]);
    }
    const missing = [...locations.keys()].filter(k => !challenges[k]);
    if (missing.length) throw new Error(`No checklist item for ${missing.sort().join(", ")} in the challenge map`);
    const lost = Object.keys(challenges).filter(k => !challenges[k].skip && !locations.has(k));
    if (lost.length) throw new Error(`No marked line is left in the prepared tree for ${lost.sort().join(", ")}`);
    const defects = new Map<string, string[]>();
    for (const key of [...locations.keys()].sort()) {
        if (challenges[key].skip) continue;
        const c = challenges[key];
        const at = `${c.checklistItem} ${(c.alsoItems ?? []).join(" ")}\n${JSON.stringify(locations.get(key))}`;
        defects.set(at, [...(defects.get(at) ?? []), key]);
    }
    return [...defects.values()].map(keys => {
        const c = challenges[keys[0]];
        const [first, ...rest] = locations.get(keys[0])!;
        return {
            id: `JS-${keys.join("+")}`,
            aspect: c.aspect,
            checklistItem: c.checklistItem,
            ...(c.alsoItems?.length ? { alsoItems: c.alsoItems } : {}),
            kind: "finding" as const,
            severity: c.severity,
            title: c.title,
            ...first,
            ...(rest.length ? { also: rest } : {})
        };
    });
}

/** The key file, bound to the trees it was read from: `pnpm eval` refuses a prep that gives another SHA. */
export function keyYaml(fixture: string, entries: KeyEntry[], shas: { upstreamSha: string; preparedSha: string }): string {
    return `# Generated by evals/key.ts from the fixture's markers, in the prepared tree's line numbers. Do not edit.\n${stringify(
        { fixture, ...shas, entries, known: [] },
        { lineWidth: 0 }
    )}`;
}
